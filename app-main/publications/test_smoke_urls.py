ADMIN_NAMES_COVERED = {'admin:index', 'admin:login'}


def url_patterns():
    """(namespaced name or None, route) of every pattern of the resolved URLconf."""
    found = []

    def walk(patterns, prefix, namespace):
        for p in patterns:
            if isinstance(p, URLResolver):
                ns = namespace
                if p.namespace:
                    ns = f'{namespace}:{p.namespace}' if namespace else p.namespace
                walk(p.url_patterns, prefix + str(p.pattern), ns)
            elif isinstance(p, URLPattern):
                name = p.name and (f'{namespace}:{p.name}' if namespace else p.name)
                found.append((name, prefix + str(p.pattern)))

    walk(get_resolver().url_patterns, '', None)
    return found


def is_admin(name, route):
    return (name or '').startswith('admin:') or route.startswith('admin/')


class SmokeUrlTests(TestCase):

    @classmethod
    def setUpClass(cls):
        cls.media_root = tempfile.mkdtemp(prefix='find_artek_smoke_media_')
        cls.media_override = override_settings(MEDIA_ROOT=cls.media_root)
        cls.media_override.enable()
        super().setUpClass()

    @classmethod
    def tearDownClass(cls):
        super().tearDownClass()
        cls.media_override.disable()
        shutil.rmtree(cls.media_root, ignore_errors=True)

    @classmethod
    def setUpTestData(cls):
        cls.author = Person.objects.create(first='Smoke', last='Author')
        cls.pub = make_report(report_type(), '99-50', verified=True, confidential=False,
                              year=1999, authors=[cls.author])
        cls.feature = Feature.objects.create(name='Smoke feature',
                                             date=datetime.date(1999, 7, 1))
        cls.feature.publications.add(cls.pub)
        cls.users = {
            'anonymous': None,
            'dtu_user': make_user('s990950'),
            'artek_editor': make_user('smked', ARTEK_EDITOR),
        }
        # Thumbnail of the public report by number (media_access: reports/<year>/thumbs/).
        cls.thumbnail = 'reports/1999/thumbs/99-50_thumb.jpg'
        full = os.path.join(cls.media_root, *cls.thumbnail.split('/'))
        os.makedirs(os.path.dirname(full), exist_ok=True)
        with open(full, 'wb') as f:
            f.write(b'\xff\xd8\xff\xe0smoke\xff\xd9')

    # --- coverage of the URLconf

    def test_every_named_url_has_a_smoke_entry(self):
        names = {name for name, route in url_patterns()
                 if name and (not is_admin(name, route) or name in ADMIN_NAMES_COVERED)}
        self.assertEqual(sorted(names - set(SMOKE)), [],
                         'named URL pattern(s) without a SMOKE entry')
        self.assertEqual(sorted(set(SMOKE) - names), [],
                         'SMOKE entries without a URL pattern')

    def test_every_unnamed_url_is_handled(self):
        routes = {route for name, route in url_patterns()
                  if not name and not is_admin(name, route)}
        handled = set(UNNAMED) | set(UNNAMED_SKIPPED)
        self.assertEqual(sorted(routes - handled), [],
                         'unnamed URL pattern(s) neither in UNNAMED nor in UNNAMED_SKIPPED')
        self.assertEqual(sorted(set(UNNAMED) - routes), [],
                         'UNNAMED entries without a URL pattern')

    # --- the requests

    def request(self, role, url, spec):
        with transaction.atomic():
            user = self.users[role]
            if user is None:
                self.client.logout()
            else:
                self.client.force_login(user)
            send = getattr(self.client, spec['method'])
            response = send(app_path(url) + spec['query'], spec['data'], **spec['extra'])
            if response.streaming:
                # Consuming the content closes the file (FileResponse of the media view);
                # response.close() would close the DB connection inside the test.
                b''.join(response.streaming_content)
            transaction.set_rollback(True)
        return response

    def assertAnswer(self, response, expected, url):
        if expected == LOGIN:
            self.assertEqual(response.status_code, 302)
            query = urlencode({'next': url}, safe='/')
            self.assertEqual(response['Location'],
                             resolve_url(settings.LOGIN_URL) + '?' + query)
        elif isinstance(expected, Redirect):
            self.assertEqual(response.status_code, expected.status)
            location = expected.location(self)
            self.assertTrue(response['Location'].startswith(location),
                            f"{response['Location']} does not start with {location}")
        else:
            self.assertEqual(response.status_code, expected)

    def check_role(self, role):
        cases = [(name, reverse(name, kwargs=spec['kwargs'](self)), spec)
                 for name, spec in SMOKE.items()]
        cases += [(f'unnamed {route!r}', get_script_prefix() + route, spec)
                  for route, spec in UNNAMED.items()]
        for name, url, spec in cases:
            expected = spec['expected'][role]
            with self.subTest(url=name, role=role, method=spec['method'], expected=expected):
                self.assertAnswer(self.request(role, url, spec), expected, url + spec['query'])

    def test_anonymous(self):
        self.check_role('anonymous')

    def test_dtu_user(self):
        self.check_role('dtu_user')

    def test_artek_editor(self):
        self.check_role('artek_editor')
