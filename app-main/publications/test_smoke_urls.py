"""Smoke test of every URL (plan "test coverage" T5).

``SMOKE`` has one entry per named URL pattern of the resolved URLconf (find_artek/urls.py with
publications, api, publications_meta, CAS login/logout, Swagger/ReDoc, select2, media). Each
entry gives the URL kwargs and the expected answer for an anonymous user, a ``dtu_user`` and an
``artek_editor``. The point is behaviour: every page renders (no 500) and access follows the
rule (permissions.py, visibility.py). ``test_every_named_url_has_a_smoke_entry`` fails when a
named pattern has no entry (a new URL needs one) or an entry has no pattern any more.

Expected answers:
- an int: that status (no redirect);
- ``LOGIN``: 302 to LOGIN_URL (the CAS login view) with ``next`` = the requested path;
- ``Redirect(target)``: 302 (301 with ``status=301``) whose Location starts with ``target``
  (a URL name, reversed, or a callable(test) returning the URL prefix).

The smoke request is a GET, or the entry's ``method`` for POST-only URLs. Every request runs
in a rolled-back savepoint, so the entries don't change each other's data.

Patterns that are not in ``SMOKE``:
- ``admin:*`` except ``admin:index`` and ``admin:login``, and the unnamed admin patterns: they
  are generated by AdminSite and the registered ModelAdmins (one set per model) and all sit
  behind the same staff check, which ``admin:index`` covers.
- unnamed patterns: ``UNNAMED`` has an entry per unnamed pattern outside admin (the root
  redirect), and ``UNNAMED_SKIPPED`` the ones skipped, with the reason (the static files
  pattern only exists with DEBUG; nginx serves /find/static/ in production).
  ``test_every_unnamed_url_is_handled`` fails when a new unnamed pattern appears.

Access to hidden reports (confidential, unverified) per page is covered in test_pages_visibility,
test_report_access, test_write_access and test_media_access; here only a public report is used.
Fixtures are made up; the only file is a tiny generated thumbnail in a temporary MEDIA_ROOT.
"""
