class Redirect:
    """A redirect whose Location starts with ``target`` (URL name or callable(test))."""

    def __init__(self, target, status=302):
        self.target = target
        self.status = status

    def location(self, test):
        if callable(self.target):
            return self.target(test)
        return reverse(self.target)

    def __repr__(self):
        target = getattr(self.target, '__name__', self.target)
        return f'Redirect({target}, {self.status})'


def entry(kwargs, anonymous, dtu_user, artek_editor, *, method='get', data=None, query='',
          extra=None):
    """``kwargs``: callable(test) -> URL kwargs, or None for none."""
    return {
        'kwargs': kwargs or (lambda t: {}),
        'expected': {'anonymous': anonymous, 'dtu_user': dtu_user,
                     'artek_editor': artek_editor},
        'method': method, 'data': data or {}, 'query': query, 'extra': extra or {},
    }


